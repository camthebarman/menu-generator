// Generates supabase/seed.sql (public starter catalog + starter recipes) from the TypeScript seed,
// so demo mode and Supabase share one source of truth. Run: npm run gen:seed
import { writeFileSync } from 'node:fs';
import { SEED_INGREDIENTS } from '../src/seed/ingredients';
import { STARTER_RECIPES } from '../src/seed/recipes';

const q = (v: unknown) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v ?? null))}::jsonb`;
const arr = (v: string[]) => `array[${v.map(q).join(',')}]::text[]`;

const out: string[] = [
  '-- GENERATED by scripts/gen-seed-sql.ts — do not edit by hand.',
  '-- Public starter catalog and starter recipes (original content, free to use and adapt).',
  'begin;',
];
for (const i of SEED_INGREDIENTS) {
  const { orgId: _o, id, ...data } = i;
  void _o;
  out.push(`insert into public.starter_ingredients(id, data) values (${q(id)}, ${j(data)}) on conflict (id) do update set data = excluded.data;`);
}
for (const r of STARTER_RECIPES) {
  out.push(
    `insert into public.recipes(id, org_id, name, workspaces, category, tags, cuisine, description, provenance, current_version_id, produces) values (` +
      `${q(r.id)}, null, ${q(r.name)}, ${arr(r.workspaces)}, ${q(r.category)}, ${arr(r.tags)}, ${q(r.cuisine)}, ${q(r.description)}, ${j(r.provenance)}, ${q(r.currentVersionId)}, ${j(r.produces)}) on conflict (id) do nothing;`,
  );
  for (const v of r.versions) {
    out.push(
      `insert into public.recipe_versions(id, recipe_id, org_id, version, lines, yield, servings, method, equipment, active_minutes, total_minutes, allergen_status, confirmed, output_hold_days, output_hold_verified) values (` +
        `${q(v.id)}, ${q(r.id)}, null, ${v.version}, ${j(v.lines)}, ${j(v.yield)}, ${v.servings}, ${j(v.method)}, ${arr(v.equipment)}, ${v.activeMinutes ?? 'null'}, ${v.totalMinutes ?? 'null'}, ${q(v.allergenStatus)}, ${v.confirmed}, ${v.outputHoldDays ?? 'null'}, ${!!v.outputHoldVerified}) on conflict (id) do nothing;`,
    );
  }
}
out.push('commit;', '');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log(`wrote ${SEED_INGREDIENTS.length} starter ingredients and ${STARTER_RECIPES.length} starter recipes`);
